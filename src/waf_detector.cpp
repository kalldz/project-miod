WAFDetectionResult WAFDetector::detectWAF(int http_code, 
                                            const std::string& response_body,
                                            const std::map<std::string, std::string>& headers) {
    WAFDetectionResult result;
    result.detected = false;
    result.provider = WAFProvider::NONE;
    result.provider_name = "None";
    result.signature = "";
    
    for (const auto& sig : signatures_) {
        // Check status codes
        bool status_match = false;
        if (!sig.status_codes.empty()) {
            status_match = std::find(sig.status_codes.begin(), sig.status_codes.end(), http_code) 
                          != sig.status_codes.end();
        }
        
        // Check headers
        bool header_match = false;
        for (const auto& header_sig : sig.header_signatures) {
            for (const auto& header : headers) {
                if (header.first.find(header_sig) != std::string::npos ||
                    header.second.find(header_sig) != std::string::npos) {
                    header_match = true;
                    result.signature = "Header: " + header.first + ": " + header.second;
                    break;
                }
            }
            if (header_match) break;
        }
        
        // Check body
        bool body_match = false;
        std::string lower_body = response_body;
        std::transform(lower_body.begin(), lower_body.end(), lower_body.begin(), ::tolower);
        
        for (const auto& body_sig : sig.body_signatures) {
            std::string lower_sig = body_sig;
            std::transform(lower_sig.begin(), lower_sig.end(), lower_sig.begin(), ::tolower);
            
            if (lower_body.find(lower_sig) != std::string::npos) {
                body_match = true;
                result.signature = "Body signature: " + body_sig;
                break;
            }
        }
        
        // If any match found
        if (header_match || body_match || (status_match && (header_match || body_match))) {
            result.detected = true;
            result.provider = sig.provider;
            result.provider_name = getProviderName(sig.provider);
            return result;
        }
    }
    
    // Check for generic WAF indicators if no specific WAF detected
    if (http_code == 403 || http_code == 406 || http_code == 429) {
        std::string lower_body = response_body;
        std::transform(lower_body.begin(), lower_body.end(), lower_body.begin(), ::tolower);
        
        if (lower_body.find("waf") != std::string::npos ||
            lower_body.find("firewall") != std::string::npos ||
            lower_body.find("blocked") != std::string::npos ||
            lower_body.find("security") != std::string::npos) {
            result.detected = true;
            result.provider = WAFProvider::UNKNOWN;
            result.provider_name = "Unknown WAF";
            result.signature = "Generic WAF indicator detected";
        }
    }
    
    return result;
}

std::string WAFDetector::getProviderName(WAFProvider provider) {
    switch (provider) {
        case WAFProvider::NONE: return "None";
        case WAFProvider::CLOUDFLARE: return "Cloudflare";
        case WAFProvider::AWS_WAF: return "AWS WAF";
        case WAFProvider::AKAMAI: return "Akamai";
        case WAFProvider::IMPERVA: return "Imperva (Incapsula)";
        case WAFProvider::F5_BIG_IP: return "F5 BIG-IP ASM";
        case WAFProvider::SUCURI: return "Sucuri";
        case WAFProvider::WORDFENCE: return "Wordfence";
        case WAFProvider::BARRACUDA: return "Barracuda";
        case WAFProvider::FORTINET: return "Fortinet FortiWeb";
        case WAFProvider::VERCEL: return "Vercel";
        case WAFProvider::FASTLY: return "Fastly";
        case WAFProvider::INCAPSULA: return "Incapsula";
        case WAFProvider::RADWARE: return "Radware";
        case WAFProvider::SOPHOS: return "Sophos UTM";
        case WAFProvider::UNKNOWN: return "Unknown WAF";
        default: return "Unknown";
    }
}
